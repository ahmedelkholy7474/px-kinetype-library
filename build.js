#!/usr/bin/env node
// Builds library.json (what the panel downloads) from categories.json + presets/*.json.
// Also refreshes the offline copy bundled inside the extension when it sits next to this folder.
// Usage: node build.js
var fs = require("fs");
var path = require("path");

var dir = __dirname;
var categories = JSON.parse(fs.readFileSync(path.join(dir, "categories.json"), "utf8"));
var presetDir = path.join(dir, "presets");
var presets = fs.readdirSync(presetDir)
  .filter(function (f) { return /\.json$/.test(f); })
  .map(function (f) {
    var p = JSON.parse(fs.readFileSync(path.join(presetDir, f), "utf8"));
    ["id", "name", "category", "in"].forEach(function (k) {
      if (!p[k]) throw new Error(f + ": missing '" + k + "'");
    });
    if (!categories.some(function (c) { return c.id === p.category; })) {
      throw new Error(f + ": unknown category '" + p.category + "'");
    }
    return p;
  })
  .sort(function (a, b) {
    function cmp(x, y) { x = x || ""; y = y || ""; return x < y ? -1 : (x > y ? 1 : 0); }
    return ((a.order || 9999) - (b.order || 9999)) || cmp(a.added, b.added) || cmp(a.id, b.id);
  });

var enginePath = path.join(dir, "engine.json");
var lib = {
  name: "PX-Kinetype Library",
  schema: 1,
  engine: fs.existsSync(enginePath) ? JSON.parse(fs.readFileSync(enginePath, "utf8")) : undefined,
  updated: new Date().toISOString(),
  categories: categories,
  presets: presets
};

var json = JSON.stringify(lib, null, 1);
fs.writeFileSync(path.join(dir, "library.json"), json);

var bundled = path.join(dir, "..", "extension", "js", "bundled-library.js");
if (fs.existsSync(path.dirname(bundled))) {
  fs.writeFileSync(bundled, "// Offline copy of the preset library (generated by library/build.js)\nwindow.KT_BUNDLED_LIBRARY = " + json + ";\n");
}
console.log("library.json: " + presets.length + " presets, " + categories.length + " categories");
